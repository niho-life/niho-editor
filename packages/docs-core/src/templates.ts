export function findTemplate(id: string): FlowTemplate | undefined {
  return FLOW_TEMPLATES.find((template) => template.id === id);
}

/** 白紙のフローの名前（Google フォームの「無題のフォーム」と同じ考え。工程設計で書き換える）。 */
export const BLANK_FLOW_NAME = "無題";

/**
 * 工程を選ぶ前に、利用条件の照会と利用申請の判定で見積もる工程数（#18883）。既定の工程は無いので、テンプレートのうち工程の
 * いちばん多いものの数にする（どのテンプレートを選んでも足りるかを見る）。数を手で書かない。
 */
export const TEMPLATE_PLANNED_CALLS = Math.max(...FLOW_TEMPLATES.map((template) => template.steps.length));

/**
 * 白紙から作る（「工程を選ぶ」と工程設計の「＋ 追加」の白紙）。工程 1 の文字起こしだけで、工程 2 以降は工程設計で足す。
 * テンプレートからは新しいフローとして作る（P4 #18567。今のフローをテンプレートに置き換える形はやめた）。
 */
export function createBlankFlow(flowId: string): Flow {
  return { version: 1, id: flowId, name: BLANK_FLOW_NAME, revision: 1, guide: "", terms: [], samples: [], transcription: true, steps: [] };
}

/** テンプレートから新しいフローを作る（revision 1）。工程・ガイドは写しで、テンプレートの定数を変えない。 */
export function createFlowFromTemplate(template: FlowTemplate, flowId: string): Flow {
  return {
    version: 1,
    id: flowId,
    name: template.name,
    revision: 1,
    guide: template.guide,
    terms: [],
    samples: [],
    transcription: true,
    steps: template.steps.map((step) => ({ ...step })),
  };
}
